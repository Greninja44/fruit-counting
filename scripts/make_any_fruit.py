#!/usr/bin/env python
"""Build the class-agnostic 'any fruit' view of the multi-class dataset (every fruit type -> one class, 'fruit').

A single-class detector learns "fruit-ness" rather than a fixed list of species, so it can count fruit types that never appeared in
training. Images are symlinked (no copies); only label files are rewritten. The COCO val2017 test images (from
data/processed/coco_fruit) are added as a second held-out split, ``test_coco`` (only apple/orange/banana are labelled there).

    python scripts/make_any_fruit.py
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from fruitcount.utils.config import resolve_path  # noqa: E402
from fruitcount.utils.geometry import box_iou_matrix  # noqa: E402
from fruitcount.utils.log import get_logger  # noqa: E402

log = get_logger("make_any_fruit")


def relink(link: Path, target: Path) -> None:
    if link.is_symlink() or link.exists():
        link.unlink() if link.is_symlink() else shutil.rmtree(link)
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(target.resolve(), target_is_directory=True)


def rewrite_labels(src: Path, dst: Path, dup_iou: float = 0.9) -> int:
    """Relabel everything as class 0 and drop boxes that duplicate an earlier one (IoU > ``dup_iou``).

    Duplicates arise when one object carries two fruit names (e.g. 'orange' + 'grapefruit') in the source labels;
    merged into one class they would teach the detector to double count.
    """
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in src.glob("*.txt"):
        kept, boxes = [], []
        for ln in f.read_text().splitlines():
            parts = ln.split()
            if not parts:
                continue
            if len(parts) == 5:
                cx, cy, w, h = map(float, parts[1:])
                box = np.array([cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2])
            else:                                            # polygon rows: use their bounding box for the duplicate test
                xy = np.array(parts[1:], float).reshape(-1, 2)
                box = np.array([xy[:, 0].min(), xy[:, 1].min(), xy[:, 0].max(), xy[:, 1].max()])
            if boxes and box_iou_matrix(box[None], np.array(boxes)).max() > dup_iou:
                continue
            boxes.append(box)
            kept.append(" ".join(["0"] + parts[1:]))
        (dst / f.name).write_text("\n".join(kept) + ("\n" if kept else ""))
        n += len(kept)
    return n


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default="data/processed/openimages_fruit")
    ap.add_argument("--coco-test", default="data/processed/coco_fruit")
    ap.add_argument("--out", default="data/processed/any_fruit")
    a = ap.parse_args()
    src, coco, out = resolve_path(a.src), resolve_path(a.coco_test), resolve_path(a.out)
    metas = []
    for sp in ("train", "val", "test"):
        if not (src / "images" / sp).is_dir():
            continue
        relink(out / "images" / sp, src / "images" / sp)
        n = rewrite_labels(src / "labels" / sp, out / "labels" / sp)
        log.info("%s: %d boxes relabelled as 'fruit'", sp, n)
    m = pd.read_csv(src / "meta.csv")
    metas.append(m[[c for c in m.columns if not c.startswith("n_") or c in ("n_fruit", "n_crowd_regions", "n_occluded", "n_truncated")]])
    if (coco / "images" / "test").is_dir():
        relink(out / "images" / "test_coco", coco / "images" / "test")
        n = rewrite_labels(coco / "labels" / "test", out / "labels" / "test_coco")
        c = pd.read_csv(coco / "meta.csv")
        c = c[c.split == "test"].assign(split="test_coco")
        metas.append(c[[x for x in c.columns if x in metas[0].columns]])
        log.info("test_coco: %d boxes", n)
    pd.concat(metas).drop_duplicates("image").to_csv(out / "meta.csv", index=False)
    (out / "dataset.yaml").write_text(f"path: {out}\ntrain: images/train\nval: images/val\ntest: images/test\nnames:\n  0: fruit\n")
    cfg = yaml.safe_load((resolve_path("configs") / "default.yaml").read_text())
    cfg["classes"] = ["fruit"]
    cfg["pretrained_class_map"] = {"apple": "fruit", "orange": "fruit", "banana": "fruit"}
    cfg["evaluation"].update({"dataset_root": str(out.relative_to(resolve_path("."))), "split": "test"})
    (resolve_path("configs") / "any_fruit.yaml").write_text("# Generated by scripts/make_any_fruit.py\n" + yaml.safe_dump(cfg, sort_keys=False))
    log.info("done: %s ; config configs/any_fruit.yaml", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
